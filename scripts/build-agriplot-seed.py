#!/usr/bin/env python3
"""
Generate scripts/agriplot-dummy-seed.sql from the real geometries in data/*.geojson.

Each geojson file is one kabupaten (named after it). We emit:
  - one sit_admin_boundary row per file (envelope from the file's bbox)
  - one sit_plots row per feature, using the REAL geometry
Flags follow the agreed dummy rules:
  - is_not_valid      = 0  (all polygon-valid)
  - is_protected_areas= 0  (all "Outside Protected Area")
  - is_deforestation  = 1  for a deterministic subset (spread across provinces)

Run:  python3 scripts/build-agriplot-seed.py
Output overwrites scripts/agriplot-dummy-seed.sql. Review, then load on the VM:
  sudo -u postgres psql -d sustainit_db -f /var/www/averos.land/scripts/agriplot-dummy-seed.sql

Re-run this after regenerating any data file (e.g. bener_meriah).
"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
OUT = os.path.join(HERE, "agriplot-dummy-seed.sql")

ACTIVITY_ID = "a9100000-0000-4000-8000-000000000001"

# filename (without .geojson) -> (province, district, gid, plot_prefix)
FILES = {
    "bener_meriah_rev_1": ("Aceh",                "Bener Meriah",  90001, "BENER-MERIAH"),
    "bandung_barat":      ("Jawa Barat",          "Bandung Barat", 90021, "BDG-BARAT"),
    "buleleng":           ("Bali",                "Buleleng",      90031, "BULELENG"),
    "tabanan":            ("Bali",                "Tabanan",       90032, "TABANAN"),
    "ende":               ("Nusa Tenggara Timur", "Ende",          90041, "ENDE"),
}

# Deterministic deforestation-detected picks: file -> set of 0-based feature indices.
# One plot per kabupaten -> 5 detected total, spread across every province.
DEFOREST = {
    "bener_meriah_rev_1": {0},
    "bandung_barat":      {0},
    "buleleng":           {0},
    "tabanan":            {0},
    "ende":               {0},
}

STATUS_MAP = {"new": "in_progress", "verified": "certified", "certified": "certified",
              "clean": "clean"}
STATUS_ROT = ["clean", "certified", "in_progress"]


def _ring_area(r):
    a = 0.0
    for i in range(len(r) - 1):
        a += r[i][0] * r[i + 1][1] - r[i + 1][0] * r[i][1]
    return abs(a)


def to_polygon_2d(geom):
    """Normalise to a 2D GeoJSON Polygon.

    The sit_plots.polygon column is typed geometry(Polygon), so MultiPolygons
    are rejected. Every source part here is single-part; if a MultiPolygon ever
    has multiple parts we keep the largest by outer-ring area.
    """
    t = geom["type"]
    if t == "Polygon":
        rings = geom["coordinates"]
    elif t == "MultiPolygon":
        parts = geom["coordinates"]
        rings = parts[0] if len(parts) == 1 else max(parts, key=lambda p: _ring_area(p[0]))
    else:
        raise ValueError(f"unsupported geometry type: {t}")
    clean = [[[c[0], c[1]] for c in ring] for ring in rings]
    return {"type": "Polygon", "coordinates": clean}


def outer_rings(geom):
    """Return list of outer rings (each a list of [x,y]) for Polygon/MultiPolygon."""
    if geom["type"] == "MultiPolygon":
        return [poly[0] for poly in geom["coordinates"]]
    return [geom["coordinates"][0]]


def bbox(feats):
    xs, ys = [], []
    for f in feats:
        for ring in outer_rings(f["geometry"]):
            for x, y, *_ in ring:
                xs.append(x); ys.append(y)
    return min(xs), min(ys), max(xs), max(ys)


def centroid_and_area_ha(geom):
    """Area-weighted centroid + area in hectares (local planar approx)."""
    rings = outer_rings(geom)
    # reference latitude for the metric projection
    all_y = [p[1] for r in rings for p in r]
    lat0 = sum(all_y) / len(all_y)
    kx = 111320.0 * math.cos(math.radians(lat0))
    ky = 110540.0
    tot_a = 0.0
    cx = cy = 0.0
    for ring in rings:
        a = 0.0
        rx = ry = 0.0
        for i in range(len(ring) - 1):
            x1, y1 = ring[i][0], ring[i][1]
            x2, y2 = ring[i + 1][0], ring[i + 1][1]
            cross = x1 * y2 - x2 * y1
            a += cross
            rx += (x1 + x2) * cross
            ry += (y1 + y2) * cross
        if a == 0:
            continue
        tot_a += a
        cx += rx
        cy += ry
    if tot_a == 0:
        # degenerate — fall back to bbox center, area 0
        xs = [p[0] for r in rings for p in r]
        ys = [p[1] for r in rings for p in r]
        return (sum(xs) / len(xs), sum(ys) / len(ys)), 0.0
    cx /= (3.0 * tot_a)
    cy /= (3.0 * tot_a)
    area_m2 = abs(tot_a) / 2.0 * kx * ky
    return (cx, cy), area_m2 / 10000.0


def sql_str(v):
    if v is None:
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def main():
    lines = []
    w = lines.append
    w("-- Dummy AgriPlot data for the SUSTAINIT database (sustainit_db) — NOT the averos DB.")
    w("-- AUTO-GENERATED by scripts/build-agriplot-seed.py from data/*.geojson — do not edit by hand.")
    w("-- Real plot geometries, one kabupaten per file. Idempotent.")
    w("-- All polygon-valid; all Outside Protected Area; a deterministic subset deforestation-detected.")
    w("--   sudo -u postgres psql -d sustainit_db -f /var/www/averos.land/scripts/agriplot-dummy-seed.sql")
    w("")
    w("BEGIN;")
    w("-- owner name column may not exist in every deployment — ensure it before we fill it")
    w("ALTER TABLE sit_plots ADD COLUMN IF NOT EXISTS respondent_status text;")
    w("")

    prefixes = sorted({cfg[3] for cfg in FILES.values()})
    like = " OR ".join(f"plot_id LIKE '{p}-%'" for p in prefixes)
    # also clear the previous synthetic Aceh/Kalbar dummy
    like += " OR plot_id LIKE 'ACEH-DUMMY-%' OR plot_id LIKE 'KALBAR-DUMMY-%'"
    w(f"DELETE FROM sit_plots WHERE {like};")
    w("DELETE FROM sit_admin_boundary WHERE gid BETWEEN 90001 AND 90099;")
    w("")
    w("INSERT INTO sit_activity_logs (id, process_id, user_id, ip_address)")
    w(f"VALUES ('{ACTIVITY_ID}',")
    w("        (SELECT id FROM sit_process ORDER BY id LIMIT 1),")
    w("        (SELECT id FROM sit_users ORDER BY created_at LIMIT 1),")
    w("        '127.0.0.1') ON CONFLICT (id) DO NOTHING;")
    w("")

    total = 0
    defor_total = 0
    for fn, (prov, dist, gid, prefix) in FILES.items():
        path = os.path.join(DATA, fn + ".geojson")
        if not os.path.exists(path):
            w(f"-- SKIP: {fn}.geojson not found")
            continue
        d = json.load(open(path, encoding="utf-8"))
        feats = d.get("features", [])
        mnx, mny, mxx, mxy = bbox(feats)
        # pad the envelope slightly so plots sit inside the boundary
        pad = 0.02
        w(f"-- {fn}: {len(feats)} plots — {prov} / {dist}")
        w(f"INSERT INTO sit_admin_boundary (gid, gis_id, country, province, district, type, geom) "
          f"VALUES ({gid}, '{gid}', 'Indonesia', {sql_str(prov)}, {sql_str(dist)}, 'district', "
          f"ST_Multi(ST_MakeEnvelope({mnx-pad:.5f},{mny-pad:.5f},{mxx+pad:.5f},{mxy+pad:.5f},4326)));")

        for i, f in enumerate(feats):
            p = f.get("properties", {}) or {}
            geom = to_polygon_2d(f["geometry"])
            (clon, clat), area_geo = centroid_and_area_ha(geom)
            # real area if present & positive, else computed from geometry
            area = p.get("POLYGON_HA") or p.get("SURVEY_HA") or 0
            try:
                area = float(area)
            except (TypeError, ValueError):
                area = 0
            if area <= 0:
                area = area_geo
            area = round(max(area, 0.01), 2)

            crop = "coffee"  # dummy dataset is all coffee
            status_raw = str(p.get("STATUS") or "").strip().lower()
            land_status = STATUS_MAP.get(status_raw, STATUS_ROT[i % len(STATUS_ROT)])
            owner = p.get("NAME2") or p.get("owner") or f"{dist} Farmer {i+1:02d}"
            year = 2015 + (i % 9)
            plot_id = f"{prefix}-{i+1:03d}"
            is_defor = 1 if i in DEFOREST.get(fn, set()) else 0
            defor_total += is_defor
            total += 1

            gj = json.dumps(geom, separators=(",", ":"))
            w(
                "INSERT INTO sit_plots (plot_id, respondent_status, area_hectares, polygon, latlong, "
                "land_status, crop_type, planting_year, gis_id, activity_id, "
                "is_not_valid, is_deforestation, is_protected_areas) VALUES ("
                f"{sql_str(plot_id)}, {sql_str(owner)}, {area}, "
                f"ST_SetSRID(ST_GeomFromGeoJSON('{gj}'),4326), "
                f"ST_SetSRID(ST_MakePoint({clon:.6f},{clat:.6f}),4326), "
                f"{sql_str(land_status)}, {sql_str(crop)}, {year}, {gid}, {sql_str(ACTIVITY_ID)}, "
                f"0, {is_defor}, 0);"
            )
        w("")

    w("COMMIT;")
    w(f"-- {total} plots, {defor_total} deforestation-detected, all valid & outside protected.")
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"Wrote {OUT}: {total} plots ({defor_total} deforestation-detected).")


if __name__ == "__main__":
    main()
